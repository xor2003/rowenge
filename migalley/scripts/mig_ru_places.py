def _tr(name):
    # whole-name lookup first, then each part of "A-B" compounds
    if name in PLACES: return PLACES[name]
    # strip qualifiers
    for q in ("Main","East","West","Downtown","south"):
        pass
    return '-'.join(PLACES.get(p.strip(), p.strip()) for p in name.split('-'))

def translate_place(s):
    # split off trailing number: "Sinanju Rail Bridge 2"
    import re
    m = re.match(r'^(.*?)(\s+\d+)$', s)
    num = m.group(2) if m else ''
    base = m.group(1) if m else s
    # find longest matching suffix
    for suf in sorted(SUFFIXES, key=len, reverse=True):
        if base.endswith(suf):
            name = base[:-len(suf)]
            # qualifier words inside names -> hyphenated suffix
            for q,qr in ((" Main","-Главный"),(" East","-Восточный"),(" West","-Западный"),(" Downtown","-Центральный")):
                if name.endswith(q):
                    name = name[:-len(q)]
                    return "%s%s%s%s" % (SUFFIXES[suf], _tr(name), qr, num)
            return "%s%s%s" % (SUFFIXES[suf], _tr(name), num)
    return _tr(base) + num
