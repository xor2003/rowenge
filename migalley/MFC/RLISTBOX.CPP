void CRListBox::AddColumn(long width)
{
	RListBoxData& data = GetData(this);
	// RERUN: original OCX semantic — AddColumn takes character units and
	// scales them by the FontNum2 font height: width = (w*tmHeight)/16.
	if (m_hWnd) {
		CDC dc(this);
		CFont* pOldFont = nullptr;
		CWnd* pParent = GetParent();
		// RERUN: FontNum2<0 means no column font persisted — measure in the
		// ambient DC font, matching retail (~16px stock metric -> ~185px cols).
		if (pParent && data.fontNum2 >= 0) {
			CFont* pGlobalFont = ResolveGlobalFont(pParent, data.fontNum2);
			if (pGlobalFont) pOldFont = dc.SelectObject(pGlobalFont);
		}
		TEXTMETRIC tm;
		if (dc.GetTextMetrics(&tm) && tm.tmHeight > 0)
			width = (width * tm.tmHeight) / 16;
		if (pOldFont) dc.SelectObject(pOldFont);
	}
	data.colWidths.push_back(width);
}

// RERUN: persisted column from the OCX stream (A0-A8 char units + C0-C8
// flags: ==1 right-aligned, >=8 icon column). Same scaling as AddColumn.
void CRListBox::AddPersistedColumn(long charUnits, long alignFlags)
{
	RListBoxData& data = GetData(this);
	long width = charUnits;
	if (m_hWnd) {
		CDC dc(this);
		CFont* pOldFont = nullptr;
		CWnd* pParent = GetParent();
		if (pParent && data.fontNum2 >= 0) {
			CFont* pGlobalFont = ResolveGlobalFont(pParent, data.fontNum2);
			if (pGlobalFont) pOldFont = dc.SelectObject(pGlobalFont);
		}
		TEXTMETRIC tm;
		if (dc.GetTextMetrics(&tm) && tm.tmHeight > 0)
			width = (width * tm.tmHeight) / 16;
		if (pOldFont) dc.SelectObject(pOldFont);
		if (RowanDbgRadio())
			fprintf(stderr, "[rradio-addcol] this=%p fontNum2=%d tmH=%d units=%ld -> w=%ld\n",
				(void*)this, data.fontNum2, (int)tm.tmHeight, charUnits, width);
	}
	int index = (int)data.colWidths.size();
	data.colWidths.push_back(width);
	// RERUN: the C-flag is not right-alignment — retail BoB renders the
	// phase tabs (C2=C3=1) left-aligned at the column start; interpreting
	// it as right-align pushed the last tab off the window's right edge.
}

void CRListBox::SetColumnWidth(short index, long width)
{
    RListBoxData& data = GetData(this);
    if (index >= 0) {
        if (index >= (int)data.colWidths.size()) {
            data.colWidths.resize(index + 1, 100);
        }
        if (width < 0) {
            // RERUN: original OCX semantic — a negative width pins the
            // column's right edge at |width| px from the list origin.
            width = -width;
            for (int i = 0; i < index; ++i)
                width -= data.colWidths[i];
            if (width < 0) width = 0;
        } else if (m_hWnd) {
            // RERUN: original OCX semantic — positive widths are character
            // units scaled by the FontNum2 font height (width*tmHeight)/16.
            CDC dc(this);
            CFont* pOldFont = nullptr;
            CWnd* pParent = GetParent();
            if (pParent && data.fontNum2 >= 0) {
                CFont* pGlobalFont = (CFont*)pParent->SendMessage(WM_GETGLOBALFONT, data.fontNum2);
                if (pGlobalFont) pOldFont = dc.SelectObject(pGlobalFont);
            }
            TEXTMETRIC tm;
            if (dc.GetTextMetrics(&tm) && tm.tmHeight > 0)
                width = (width * tm.tmHeight) / 16;
            if (pOldFont) dc.SelectObject(pOldFont);
        }
        data.colWidths[index] = width;
    }
}

