void CRListBox::OnLButtonDown(UINT nFlags, CPoint point)
{
	RListBoxData& data = GetData(this);
	int rowHeight = GetRowHeight(this);

    CRect rect;
    GetClientRect(&rect);
    int visibleRows = rect.Height() / rowHeight;
    bool hasScrollbar = data.rowCount > visibleRows;
    int scrollWidth = 16;

    if (hasScrollbar && point.x >= rect.right - scrollWidth) {
        // Handle Scrollbar click
        int maxScroll = std::max(0, data.rowCount - visibleRows);
        if (maxScroll > 0) {
             int viewHeight = rect.Height();
             int thumbHeight = std::max(20, (viewHeight * visibleRows) / data.rowCount);
             int trackHeight = viewHeight;
             int availableTrack = trackHeight - thumbHeight;
             
             int clickY = std::max(0, (int)point.y - thumbHeight / 2);
             if (clickY > availableTrack) clickY = availableTrack;
             
             if (availableTrack > 0) {
                 data.scrollPos = (clickY * maxScroll) / availableTrack;
                 Invalidate();
             }
        }
        return;
    }

    // RERUN: Adjust row click for scroll position
	int row = (point.y / rowHeight) + data.scrollPos;

	if (row >= 0 && row < data.rowCount) {
		int col = 0;
		int x = 0;
		for (size_t i = 0; i < data.colWidths.size(); ++i) {
			x += data.colWidths[i];
			if (point.x < x) {
				col = (int)i;
				break;
			}
		}
		FireEvent(1, (long)row, (long)col);
	}
}

